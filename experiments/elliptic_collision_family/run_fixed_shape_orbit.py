"""Transport the extra-section square gate along fixed-shape elliptic orbits.

Each low-conductor rank-loss fiber has small ``c``.  Holding that arithmetic
shape fixed turns the primitive-support gate into the congruent-number curve

    E_N: y^2 = x^3 - N^2*x,       t = -x/N.

This script follows the exact Mordell--Weil recurrence generated by the known
fiber and asks whether the *second* square current recurs.  It is an orbit
calculation, not a rational-parameter box search.
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass
from fractions import Fraction
from math import isqrt

from seven_section_surface import (
    base_height_shell_forms,
    exposed_base_height_forms,
    extra_section_r_minus_s_conic,
    extra_section_r_plus_2s_carrier,
    sixth_height_shell_forms,
)


Q = Fraction
Point = tuple[Fraction, Fraction] | None


@dataclass(frozen=True)
class FixedShapeSeed:
    name: str
    c: Fraction
    t: Fraction
    squarefree_twist: int
    square_scale: Fraction


SEEDS = (
    FixedShapeSeed("quarter", Q(-12, 7), Q(1, 4), 15, Q(2, 7)),
    FixedShapeSeed("fifth", Q(-10, 7), Q(1, 5), 30, Q(1, 7)),
    FixedShapeSeed("seventh", Q(21, 4), Q(1, 7), 21, Q(5, 4)),
    FixedShapeSeed("ninth", Q(-49, 4), Q(1, 9), 5, Q(21, 4)),
    FixedShapeSeed("eleventh", Q(6, 49), Q(1, 11), 330, Q(1, 49)),
)


def rational_square_root(value: Fraction) -> Fraction | None:
    if value < 0:
        return None
    numerator = isqrt(value.numerator)
    denominator = isqrt(value.denominator)
    if numerator * numerator != value.numerator:
        return None
    if denominator * denominator != value.denominator:
        return None
    return Q(numerator, denominator)


def add_points(left: Point, right: Point, twist: int) -> Point:
    if left is None:
        return right
    if right is None:
        return left
    x1, y1 = left
    x2, y2 = right
    if x1 == x2 and y1 == -y2:
        return None
    if left == right:
        slope = (3 * x1 * x1 - twist * twist) / (2 * y1)
    else:
        slope = (y2 - y1) / (x2 - x1)
    x3 = slope * slope - x1 - x2
    return x3, slope * (x1 - x3) - y1


def seed_point(seed: FixedShapeSeed) -> tuple[Fraction, Fraction]:
    support = rational_square_root(
        seed.squarefree_twist * seed.t * (1 - seed.t * seed.t)
    )
    if support is None:
        raise AssertionError("the stated fixed-shape seed lost its support square")
    point = (-seed.squarefree_twist * seed.t, seed.squarefree_twist * support)
    x, y = point
    assert y * y == x**3 - seed.squarefree_twist**2 * x
    assert seed.c * (seed.c + 1) == (
        seed.square_scale * seed.square_scale * seed.squarefree_twist
    )
    return point


def orbit_hits(
    seed: FixedShapeSeed, count: int
) -> tuple[tuple[str, str, int, Fraction], ...]:
    generator = seed_point(seed)
    point: Point = None
    hits = []
    torsion_cosets: tuple[tuple[str, Point], ...] = (
        ("O", None),
        ("T0", (Q(0), Q(0))),
        ("T+", (Q(seed.squarefree_twist), Q(0))),
        ("T-", (Q(-seed.squarefree_twist), Q(0))),
    )
    for index in range(1, count + 1):
        point = add_points(point, generator, seed.squarefree_twist)
        if point is None:
            continue
        for coset, torsion in torsion_cosets:
            translated = add_points(point, torsion, seed.squarefree_twist)
            if translated is None:
                continue
            t = -translated[0] / seed.squarefree_twist
            if rational_square_root(extra_section_r_minus_s_conic(seed.c, t)) is not None:
                hits.append(("r-s", coset, index, t))
            if rational_square_root(extra_section_r_plus_2s_carrier(seed.c, t)) is not None:
                hits.append(("r+2s", coset, index, t))
    return tuple(hits)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--multiples", type=int, default=12)
    args = parser.parse_args()
    for seed in SEEDS:
        hits = orbit_hits(seed, args.multiples)
        print("shape=", seed.name, "N=", seed.squarefree_twist)
        for current, coset, index, t in hits:
            safe = all(
                base_height_shell_forms(seed.c, t)
                + exposed_base_height_forms(seed.c, t)
            )
            if current == "r-s":
                safe = safe and all(sixth_height_shell_forms(seed.c, t))
            print(
                " current=", current,
                "coset=", coset,
                " multiple=", index,
                "t=", t,
                "height_safe=", safe,
                "parameter_bits=", t.numerator.bit_length() + t.denominator.bit_length(),
            )


if __name__ == "__main__":
    main()

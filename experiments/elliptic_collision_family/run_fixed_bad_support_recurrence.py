"""Preserve the near-miss bad-prime support while moving the shape current.

At ``t=1/9`` both the essential discriminant and the hidden ``x=3*r/2``
carrier depend on ``u=c*(c+1)``.  The sub-record rank-five fiber ``c=1/8``
has ``u=9/64`` and

    P(u) = 76800*u^3 - 2595361*u^2 + 230400*u + 76800
         = 3*419*3863*(7/64)^2.

Consequently the cubic twist

    N*v^2 = P(u),  N=3*419*3863,

is the exact fixed-bad-support deformation through the near miss.  Its group
law changes the shape without introducing a new squarefree factor in the
essential discriminant.  This module follows only the cyclic recurrence
generated by the known point and tests the two independent square gates

    d^2 = 1+4*u,
    y^2 = u*(601*u+1350).

Their simultaneous recurrence restores a rational ``c`` and the hidden
sixth section.  This is a Mordell--Weil recurrence, not a rational grid scan.
"""

from __future__ import annotations

from fractions import Fraction
from math import isqrt
from typing import Optional


Q = Fraction
Point = Optional[tuple[Fraction, Fraction]]

BAD_SUPPORT = 3 * 419 * 3863
CUBIC_A = 76800
CUBIC_B = -2595361
CUBIC_C = 230400
CUBIC_D = 76800

# For Y0^2=N*P(u), X=A*u and Y=A*Y0 with A=N*CUBIC_A.
SCALE_X = BAD_SUPPORT * CUBIC_A
A2 = BAD_SUPPORT * CUBIC_B
A4 = (BAD_SUPPORT**2) * CUBIC_A * CUBIC_C
A6 = (BAD_SUPPORT**3) * (CUBIC_A**2) * CUBIC_D


def rational_square_root(value: Fraction) -> Fraction | None:
    if value < 0:
        return None
    numerator = isqrt(value.numerator)
    denominator = isqrt(value.denominator)
    if numerator * numerator != value.numerator:
        return None
    if denominator * denominator != value.denominator:
        return None
    return Q(numerator, denominator)


def add_points(left: Point, right: Point) -> Point:
    """Group law on ``Y^2=X^3+A2*X^2+A4*X+A6``."""

    if left is None:
        return right
    if right is None:
        return left
    x1, y1 = left
    x2, y2 = right
    if x1 == x2 and y1 == -y2:
        return None
    if left == right:
        slope = (3 * x1 * x1 + 2 * A2 * x1 + A4) / (2 * y1)
    else:
        slope = (y2 - y1) / (x2 - x1)
    x3 = slope * slope - A2 - x1 - x2
    return x3, slope * (x1 - x3) - y1


def point_from_uv(u: Fraction, v: Fraction) -> tuple[Fraction, Fraction]:
    x = SCALE_X * u
    y = BAD_SUPPORT * SCALE_X * v
    assert y * y == x**3 + A2 * x * x + A4 * x + A6
    return x, y


SEED = point_from_uv(Q(9, 64), Q(7, 64))


def shape_from_point(point: tuple[Fraction, Fraction]) -> Fraction:
    return point[0] / SCALE_X


def carrier_gates(u: Fraction) -> tuple[Fraction | None, Fraction | None]:
    return (
        rational_square_root(1 + 4 * u),
        rational_square_root(u * (601 * u + 1350)),
    )


def recurrent_hits(count: int) -> tuple[tuple[int, Fraction, Fraction, Fraction], ...]:
    """Return simultaneous square-gate hits among the first ``count`` multiples."""

    point: Point = None
    hits = []
    for index in range(1, count + 1):
        point = add_points(point, SEED)
        if point is None:
            continue
        u = shape_from_point(point)
        d, y = carrier_gates(u)
        if d is not None and y is not None:
            hits.append((index, u, d, y))
    return tuple(hits)


def main() -> None:
    hits = recurrent_hits(32)
    for index, u, d, y in hits:
        c = (d - 1) / 2
        print(
            "multiple=", index,
            "u=", u,
            "c=", c,
            "carrier_y=", y,
            "bits=", max(u.numerator.bit_length(), u.denominator.bit_length()),
        )


if __name__ == "__main__":
    main()

def gauge(w):
    lines = [f'BRUUN_ALWAYS_INLINE void gauge{w}(double* RESTRICT v, int d) const {{',
             '#if BRUUN_LEVEL >= 1']
    for j in range(0, w, 2):
        lines += [f'const auto a{j} = V2_LD(v+{j}), b{j} = V2_LD(v+{w+j});',
                  f'auto z{j} = V2_UNPLO(a{j}, b{j});',
                  f'auto z{j+1} = V2_UNPHI(a{j}, b{j});']
    for j in range(1,w):
        lines += [f'const auto t{j} = V2_LD(cs_.data()+2*static_cast<std::size_t>({j}*d));',
                  f'z{j} = V2_MADD(V2_MUL(V2_DUP0(t{j}), z{j}), V2_DUP1(t{j}), V2_SWAP(V2_NEGHI(z{j})));']
    serial = [0]
    def fft(z):
        n = len(z)
        if n == 1: return z
        even, odd = fft(z[::2]), fft(z[1::2])
        out = [''] * n
        for k in range(n//2):
            a,b = even[k],odd[k]
            if k:
                serial[0] += 1; r = f'r{serial[0]}'
                if 4*k == n:
                    lines.append(f'const auto {r} = V2_SWAP(V2_NEGHI({b}));')
                else:
                    c,s = math.cos(2*math.pi*k/n),math.sin(2*math.pi*k/n)
                    lines.append(f'const auto {r} = V2_MADD(V2_MUL(V2_SET1({c:.17g}), {b}), V2_SET1({s:.17g}), V2_SWAP(V2_NEGHI({b})));')
                b=r
            serial[0] += 1; l=f'f{serial[0]}'
            serial[0] += 1; h=f'f{serial[0]}'
            lines.extend([f'const auto {l} = V2_ADD({a}, {b});',f'const auto {h} = V2_SUB({a}, {b});'])
            out[k],out[k+n//2]=l,h
        return out
    out=fft([f'z{j}' for j in range(w)])
    def leaves(d,e,width):
        return [d] if width==1 else leaves(d,e*2,width//2)+leaves(e-d,e*2,width//2)
    for p,k in enumerate(leaves(1,16,w)):
        conj=k%16 != 1
        m=((16*w-k if conj else k)-1)//16
        expr=f'V2_NEGHI({out[m]})' if conj else out[m]
        lines.append(f'V2_ST(v+{2*p}, {expr});')
    lines += ['#else', f'fwd_span_reference(v, {w}, d, n_/{w});', '#endif','}']
    return '\n'.join(lines)


def _mse(estimate: Array, truth: Array, mask: Array | None = None) -> float:
    residual = np.asarray(estimate) - np.asarray(truth)
    if mask is not None:
        residual = residual[mask]
    return float(np.mean(residual * residual))


def _excursion(estimate: Array, source: Array) -> float:
    low, high = float(np.min(source)), float(np.max(source))
    return max(
        float(np.max(low - estimate, initial=0.0)),
        float(np.max(estimate - high, initial=0.0)),
    )


def _sign_changes(value: Array) -> int:
    value = np.asarray(value, dtype=np.float64)
    tolerance = 1024.0 * np.finfo(np.float64).eps * max(
        1.0, float(np.max(np.abs(value), initial=0.0))
    )
    sign = np.sign(value[np.abs(value) > tolerance])
    return int(np.sum(sign[1:] != sign[:-1]))


def _conv_line(source: Array, scale: int = 2) -> Array:
    profile = _quintic_variation_lineage_profile(source)
    return np.stack([
        _evaluate_quintic_variation_lineage_profile(profile, i / scale)
        for i in range((source.shape[0] - 1) * scale + 1)
    ])


def _raw_quintic_profile(values: Array) -> tuple[Array, Array]:
    """Return the unprojected quintic generated by the compact two-jet."""

    source, first, second = _local_fourth_order_2jet(values)
    intervals = source.shape[0] - 1
    control = np.empty((intervals, 6) + source.shape[1:], dtype=np.float64)
    control[:, 0] = source[:-1]
    control[:, 1] = source[:-1] + first[:-1] / 5.0
    control[:, 2] = source[:-1] + 2.0 * first[:-1] / 5.0 + second[:-1] / 20.0
    control[:, 5] = source[1:]
    control[:, 4] = source[1:] - first[1:] / 5.0
    control[:, 3] = source[1:] - 2.0 * first[1:] / 5.0 + second[1:] / 20.0
    return source, np.diff(control, axis=1)


def _raw_quintic_line(source: Array, scale: int = 2) -> Array:
    profile = _raw_quintic_profile(source)
    return np.stack([
        _evaluate_quintic_variation_lineage_profile(profile, i / scale)
        for i in range((source.shape[0] - 1) * scale + 1)
    ])


def _linear_line(source: Array, scale: int = 2) -> Array:
    coordinate = np.arange((source.shape[0] - 1) * scale + 1) / scale
    return np.interp(coordinate, np.arange(source.shape[0]), source)


def _lanczos_line(source: Array, scale: int = 2, radius: int = 3) -> Array:
    coordinate = np.arange((source.shape[0] - 1) * scale + 1) / scale
    nodes = np.arange(source.shape[0], dtype=np.float64)
    output = np.empty(coordinate.shape, dtype=np.float64)
    for index, point in enumerate(coordinate):
        distance = point - nodes
        admitted = np.abs(distance) < radius
        weight = np.zeros_like(nodes)
        weight[admitted] = (
            np.sinc(distance[admitted])
            * np.sinc(distance[admitted] / radius)
        )
        weight /= np.sum(weight)
        output[index] = weight @ source
    return output


def _interior_held_out_mask(side: int, scale: int = 2) -> Array:
    mask = np.ones((side, side), dtype=bool)
    mask[::scale, ::scale] = False
    crop = 2 * scale
    mask[:crop] = False
    mask[-crop:] = False
    mask[:, :crop] = False
    mask[:, -crop:] = False
    return mask


def _line_mask(side: int, scale: int = 2) -> Array:
    mask = np.ones(side, dtype=bool)
    mask[::scale] = False
    mask[: 2 * scale] = False
    mask[-2 * scale :] = False
    return mask


def _line_cases() -> list[tuple[str, dict[str, float]]]:
    cases: list[tuple[str, dict[str, float]]] = []
    phases = np.arange(8, dtype=np.float64) * math.pi / 4.0
    for frequency in (0.75, 1.5, 2.25, 3.0):
        for phase in phases:
            cases.append(("carrier", {"frequency": frequency, "phase": phase}))
    for center in (0.44, 0.48, 0.52, 0.56):
        for width in (0.025, 0.05):
            cases.append(("edge", {"center": center, "width": width}))
            cases.append(("bump", {"center": center, "width": width * 1.8}))
    for phase in phases:
        cases.append(("chirp", {"phase": phase}))
    return cases


def _line_truth(kind: str, parameters: dict[str, float], side: int) -> Array:
    x = np.linspace(0.0, 1.0, side)
    if kind == "carrier":
        return 0.5 + 0.38 * np.sin(
            2.0 * math.pi * parameters["frequency"] * x
            + parameters["phase"]
        )
    if kind == "edge":
        return 0.5 + 0.45 * np.tanh(
            (x - parameters["center"]) / parameters["width"]
        )
    if kind == "bump":
        return 0.08 + 0.84 * np.exp(
            -((x - parameters["center"]) / parameters["width"]) ** 2
        )
    if kind == "chirp":
        return 0.5 + 0.34 * np.sin(
            2.0 * math.pi * (0.5 * x + 2.5 * x * x)
            + parameters["phase"]
        )
    raise KeyError(kind)


def _line_fidelity(sizes: tuple[int, ...]) -> list[dict[str, object]]:
    records: list[dict[str, object]] = []
    operations = {
        "CONV": _conv_line,
        "Raw 2-jet": _raw_quintic_line,
        "Lanczos-3": _lanczos_line,
        "bilinear": _linear_line,
    }
    for source_side in sizes:
        truth_side = 2 * (source_side - 1) + 1
        mask = _line_mask(truth_side)
        for case_index, (kind, parameters) in enumerate(_line_cases()):
            truth = _line_truth(kind, parameters, truth_side)
            source = truth[::2]
            metrics: dict[str, object] = {}
            for method, operation in operations.items():
                estimate = operation(source, 2)
                metrics[method] = {
                    "mse": _mse(estimate, truth, mask),
                    "linf": float(np.max(np.abs(estimate[mask] - truth[mask]))),
                    "excursion": _excursion(estimate, source),
                    "sample_error": float(np.max(np.abs(estimate[::2] - source))),
                }
            records.append({
                "source_side": source_side,
                "case_index": case_index,
                "kind": kind,
                "parameters": parameters,
                "metrics": metrics,
            })
    return records


def _topology_stress(sizes: tuple[int, ...]) -> list[dict[str, object]]:
    records: list[dict[str, object]] = []
    operations = {
        "CONV": _conv_line,
        "Raw 2-jet": _raw_quintic_line,
        "Lanczos-3": _lanczos_line,
        "bilinear": _linear_line,
    }
    for source_side in sizes:
        for kind in ("step", "box"):
            for phase_index in range(16):
                shift = (phase_index + 0.5) / 16.0
                x = np.arange(source_side, dtype=np.float64)
                if kind == "step":
                    source = (x >= source_side / 2.0 - 0.5 + shift).astype(float)
                else:
                    center = source_side / 2.0 - 0.5 + shift
                    source = (np.abs(x - center) <= source_side / 6.0).astype(float)
                source_variation = _sign_changes(np.diff(source))
                metrics: dict[str, object] = {}
                for method, operation in operations.items():
                    estimate = operation(source, 8)
                    variation = _sign_changes(np.diff(estimate))
                    metrics[method] = {
                        "sign_surplus": max(0, variation - source_variation),
                        "excursion": _excursion(estimate, source),
                    }
                records.append({
                    "source_side": source_side,
                    "kind": kind,
                    "phase_index": phase_index,
                    "metrics": metrics,
                })
    return records


def _scene(
    kind: str,
    side: int,
    *,
    angle: float = 0.0,
    phase: float = 0.0,
    offset: float = 0.0,
) -> Array:
    axis = np.linspace(0.0, 1.0, side)
    y, x = np.meshgrid(axis, axis, indexing="ij")
    theta = math.radians(angle)
    along = x * math.cos(theta) + y * math.sin(theta)
    normal = (x - 0.5) * math.cos(theta) + (y - 0.5) * math.sin(theta)
    if kind == "edge":
        return 0.5 + 0.43 * np.tanh((normal - offset) / 0.035)
    if kind == "carrier":
        envelope = np.sin(math.pi * x) ** 2 * np.sin(math.pi * y) ** 2
        return 0.5 + 0.34 * envelope * np.sin(
            2.0 * math.pi * 3.25 * along + phase
        )
    if kind == "curved":
        radius = np.hypot(x - 0.47, y - 0.53)
        return 0.5 + 0.42 * np.tanh((radius - 0.27 - offset) / 0.032)
    if kind == "crossing":
        first = np.sin(2.0 * math.pi * (2.75 * x + 0.9 * y) + phase)
        second = np.sin(2.0 * math.pi * (-0.9 * x + 2.75 * y) - phase)
        return 0.5 + 0.19 * (first + second)
    raise KeyError(kind)


def _two_dimensional_cases(source_side: int) -> list[dict[str, float | str]]:
    h = 1.0 / (source_side - 1)
    cases: list[dict[str, float | str]] = []
    for angle in (7.5, 22.5, 37.5, 52.5, 67.5, 82.5):
        for signed_phase in (-0.25, 0.25):
            cases.append({
                "kind": "edge", "angle": angle,
                "phase": 0.0, "offset": signed_phase * h,
            })
        for phase in (0.0, math.pi / 2.0):
            cases.append({
                "kind": "carrier", "angle": angle,
                "phase": phase, "offset": 0.0,
            })
    for signed_phase in (-0.25, 0.25):
        cases.append({
            "kind": "curved", "angle": 0.0,
            "phase": 0.0, "offset": signed_phase * h,
        })
    for phase in (0.0, math.pi / 2.0):
        cases.append({
            "kind": "crossing", "angle": 0.0,
            "phase": phase, "offset": 0.0,
        })
    return cases


def _conv_reverse(source: Array) -> Array:
    field = np.asarray(source, dtype=np.float64)[..., None]
    along_y = _refine_profile_axis(
        field, 0, 2,
        _quintic_variation_lineage_profile,
        _evaluate_quintic_variation_lineage_profile,
    )
    output = _refine_profile_axis(
        along_y, 1, 2,
        _quintic_variation_lineage_profile,
        _evaluate_quintic_variation_lineage_profile,
    )
    return output[..., 0]


def _tensor_resize_with_profile(
    samples: Array,
    scale: int,
    profile_builder: object,
) -> Array:
    field = np.asarray(samples, dtype=np.float64)
    scalar = field.ndim == 2
    if scalar:
        field = field[..., None]
    along_x = _refine_profile_axis(
        field, 1, scale, profile_builder,
        _evaluate_quintic_variation_lineage_profile,
    )
    output = _refine_profile_axis(
        along_x, 0, scale, profile_builder,
        _evaluate_quintic_variation_lineage_profile,
    )
    return output[..., 0] if scalar else output


def _raw_quintic_resize(samples: Array, scale: int = 2) -> Array:
    return _tensor_resize_with_profile(samples, scale, _raw_quintic_profile)


def _easu_nested_resize(samples: Array, scale: int) -> Array:
    """Evaluate EASU directly on an endpoint-aligned display lattice."""

    source = np.asarray(samples, dtype=np.float64)
    if source.ndim != 2:
        raise ValueError("dense EASU display expects a scalar field")
    color = np.repeat(source[..., None], 3, axis=2)
    target_side = (source.shape[0] - 1) * scale + 1
    output = np.empty((target_side, target_side), dtype=np.float64)
    for row in range(target_side):
        for column in range(target_side):
            output[row, column] = easu_at_source_coordinate(
                color, column / scale, row / scale
            )[0]
    return output


def _two_dimensional_fidelity(
    sizes: tuple[int, ...], *, include_easu: bool
) -> tuple[list[dict[str, object]], dict[str, dict[str, Array]]]:
    records: list[dict[str, object]] = []
    plate: dict[str, dict[str, Array]] = {}
    for source_side in sizes:
        truth_side = 2 * (source_side - 1) + 1
        mask = _interior_held_out_mask(truth_side)
        for case_index, case in enumerate(_two_dimensional_cases(source_side)):
            truth = _scene(case["kind"], truth_side, angle=case["angle"],
                           phase=case["phase"], offset=case["offset"])
            source = truth[::2, ::2]
            estimates = {
                "CONV*": distilled_conv_synthesis(source, truth.shape),
                "Raw 2-jet": _raw_quintic_resize(source, 2),
                "Lanczos-3": lanczos_resize(source, 2, radius=3),
                "bilinear": bilinear_resample_to_shape(source, truth.shape),
            }
            if include_easu:
                estimates["EASU"] = easu_nested_2x(source)
            reverse = _conv_reverse(source)
            metrics: dict[str, object] = {}
            for method, estimate in estimates.items():
                metrics[method] = {
                    "mse": _mse(estimate, truth, mask),
                    "linf": float(np.max(np.abs(estimate[mask] - truth[mask]))),
                    "excursion": _excursion(estimate, source),
                    "sample_error": float(np.max(np.abs(
                        estimate[::2, ::2] - source
                    ))),
                }

            record = {
                "source_side": source_side,
                "case_index": case_index,
                "case": case,
                "metrics": metrics,
                "order_maximum_delta": float(np.max(np.abs(
                    estimates["CONV*"] - reverse
                ))),
                "reverse_order_mse": _mse(reverse, truth, mask),
            }
            records.append(record)

            if source_side == 17:
                selected = (
                    (case["kind"] == "edge" and case["angle"] == 37.5
                     and case["offset"] > 0.0)
                    or (case["kind"] == "carrier" and case["angle"] == 37.5
                        and case["phase"] > 0.0)
                    or (case["kind"] == "curved" and case["offset"] > 0.0)
                    or (case["kind"] == "crossing" and case["phase"] > 0.0)
                )
                if selected:
                    display_scale = 32
                    display_side = display_scale * (source_side - 1) + 1
                    display_truth = _scene(
                        case["kind"], display_side, angle=case["angle"],
                        phase=case["phase"], offset=case["offset"],
                    )
                    plate[str(case["kind"])] = {
                        "truth": display_truth,
                        "CONV*": distilled_conv_synthesis(
                            source, display_truth.shape
                        ),
                        "Lanczos-3": lanczos_resize(
                            source, display_scale, radius=3
                        ),
                        "bilinear": bilinear_resample_to_shape(
                            source, display_truth.shape
                        ),
                        "EASU": _easu_nested_resize(source, display_scale),
                    }
    return records, plate


def _binary64_audit() -> dict[str, float | int]:
    rng = np.random.default_rng(20260826)
    maximum_mass_residual = 0.0
    maximum_cardinal_error = 0.0
    maximum_lifting_error = 0.0
    maximum_sign_surplus = 0
    trial_count = 0
    for side in (5, 9, 17, 33, 65):
        for _ in range(16):
            source = rng.normal(size=(side, 3))
            anchored, current = _quintic_variation_lineage_profile(source)
            maximum_mass_residual = max(
                maximum_mass_residual,
                float(np.max(np.abs(
                    np.sum(current, axis=1) - np.diff(source, axis=0)
                ))),
            )
            for channel in range(source.shape[1]):
                maximum_sign_surplus = max(
                    maximum_sign_surplus,
                    _sign_changes(current[:, :, channel].reshape(-1))
                    - _sign_changes(np.diff(source[:, channel])),
                )
            refined = _conv_line(source, 2)
            maximum_cardinal_error = max(
                maximum_cardinal_error,
                float(np.max(np.abs(refined[::2] - anchored))),
            )
            fine = rng.normal(size=(2 * side - 1, 3))
            coarse, detail = quintic_variation_lifting_analysis(fine)
            returned = quintic_variation_lifting_synthesis(coarse, detail)
            maximum_lifting_error = max(
                maximum_lifting_error,
                float(np.max(np.abs(returned - fine))),
            )
            trial_count += 1
    return {
        "trial_count": trial_count,
        "maximum_current_mass_residual": maximum_mass_residual,
        "maximum_cardinal_error": maximum_cardinal_error,
        "maximum_lifting_round_trip_error": maximum_lifting_error,
        "maximum_sign_variation_surplus": maximum_sign_surplus,
    }


def _geometric_mean(values: Array) -> float:
    values = np.asarray(values, dtype=np.float64)
    return float(np.exp(np.mean(np.log(np.maximum(values, 1.0e-300)))))


def _summarize(
    one_d: list[dict[str, object]],
    topology: list[dict[str, object]],
    two_d: list[dict[str, object]],
) -> dict[str, object]:
    result: dict[str, object] = {"one_dimensional": {}, "two_dimensional": {}}
    for source_side in sorted({int(row["source_side"]) for row in one_d}):
        group = [row for row in one_d if row["source_side"] == source_side]
        methods: dict[str, object] = {}
        for method in ("CONV", "Raw 2-jet", "Lanczos-3", "bilinear"):
            values = np.array([row["metrics"][method]["mse"] for row in group])
            methods[method] = {
                "geometric_mean_mse": _geometric_mean(values),
                "median_mse": float(np.median(values)),
                "maximum_mse": float(np.max(values)),
            }
        conv = np.array([row["metrics"]["CONV"]["mse"] for row in group])
        lanczos = np.array([
            row["metrics"]["Lanczos-3"]["mse"] for row in group
        ])
        result["one_dimensional"][str(source_side)] = {
            "case_count": len(group),
            "methods": methods,
            "conv_wins_ties_losses_vs_lanczos3": [
                int(np.sum(conv < lanczos)), int(np.sum(conv == lanczos)),
                int(np.sum(conv > lanczos)),
            ],
            "geometric_mean_mse_ratio_conv_over_lanczos3": _geometric_mean(
                conv / np.maximum(lanczos, 1.0e-300)
            ),
        }

    for source_side in sorted({int(row["source_side"]) for row in two_d}):
        group = [row for row in two_d if row["source_side"] == source_side]
        methods: dict[str, object] = {}
        available = tuple(group[0]["metrics"].keys())
        for method in available:
            values = np.array([row["metrics"][method]["mse"] for row in group])
            methods[method] = {
                "geometric_mean_mse": _geometric_mean(values),
                "median_mse": float(np.median(values)),
                "maximum_excursion": float(max(
                    row["metrics"][method]["excursion"] for row in group
                )),
                "maximum_sample_error": float(max(
                    row["metrics"][method]["sample_error"] for row in group
                )),
            }
        conv = np.array([row["metrics"]["CONV*"]["mse"] for row in group])
        lanczos = np.array([
            row["metrics"]["Lanczos-3"]["mse"] for row in group
        ])
        result["two_dimensional"][str(source_side)] = {
            "case_count": len(group),
            "methods": methods,
            "conv_wins_ties_losses_vs_lanczos3": [
                int(np.sum(conv < lanczos)), int(np.sum(conv == lanczos)),
                int(np.sum(conv > lanczos)),
            ],
            "geometric_mean_mse_ratio_conv_over_lanczos3": _geometric_mean(
                conv / np.maximum(lanczos, 1.0e-300)
            ),
            "maximum_factor_order_delta": float(max(
                row["order_maximum_delta"] for row in group
            )),
            "geometric_mean_factor_order_delta": _geometric_mean(np.array([
                row["order_maximum_delta"] for row in group
            ])),
        }

    topology_summary: dict[str, object] = {}
    for source_side in sorted({int(row["source_side"]) for row in topology}):
        group = [row for row in topology if row["source_side"] == source_side]
        topology_summary[str(source_side)] = {
            method: {
                "cases_with_sign_surplus": int(sum(
                    row["metrics"][method]["sign_surplus"] > 0 for row in group
                )),
                "maximum_sign_surplus": int(max(
                    row["metrics"][method]["sign_surplus"] for row in group
                )),
                "maximum_excursion": float(max(
                    row["metrics"][method]["excursion"] for row in group
                )),
            }
            for method in ("CONV", "Raw 2-jet", "Lanczos-3", "bilinear")
        }
    result["topology"] = topology_summary
    return result


def _plot_convergence(summary: dict[str, object], output: Path) -> None:
    plt.rcParams.update({
        "font.size": 8,
        "axes.labelsize": 8,
        "axes.titlesize": 8,
        "legend.fontsize": 7,
        "pdf.fonttype": 42,
    })
    figure, axes = plt.subplots(1, 2, figsize=(7.08, 2.55))
    for axis, dimension, title in zip(
        axes,
        ("one_dimensional", "two_dimensional"),
        ("1-D phase/profile census", "2-D orientation/phase census"),
    ):
        table = summary[dimension]
        sizes = np.array(sorted(map(int, table)), dtype=float)
        available = table[str(int(sizes[0]))]["methods"].keys()
        for method in available:
            if method == "Raw 2-jet":
                continue
            values = np.array([
                table[str(int(size))]["methods"][method]["geometric_mean_mse"]
                for size in sizes
            ])
            axis.semilogy(
                sizes, values, marker="o", linewidth=1.4, markersize=3.2,
                label=method, color=COLORS[method],
            )
        axis.set_title(title)
        axis.set_xlabel("source nodes per axis")
        axis.set_ylabel("geometric mean held-out MSE")
        axis.grid(True, which="both", linewidth=0.35, alpha=0.45)
        axis.set_xticks(sizes, [str(int(value)) for value in sizes])
        axis.minorticks_off()
    for axis in axes:
        axis.legend(frameon=False)
    figure.tight_layout(pad=0.6, w_pad=1.2)
    figure.savefig(output, bbox_inches="tight", dpi=600)
    plt.close(figure)


